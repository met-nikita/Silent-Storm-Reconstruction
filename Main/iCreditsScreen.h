////////////////////////////////////////////////////////////////////////////////////////////////////
// CICCreditsScreen  --  the queued main-loop command that builds + installs the credits roll.
// Transient (a CInterfaceCommand, not save-registered -- like CICSideMenu/CICMainMenu).
// bFinalCredits = the end-game roll (replaces the stack + plays Credits.bik); false = the
// from-the-menu roll (pushed on top of the main menu, no video).  @0x1cbc50 / Exec @0x1cc850.
////////////////////////////////////////////////////////////////////////////////////////////////////
class CICCreditsScreen: public NMainLoop::CInterfaceCommand
{
	OBJECT_BASIC_METHODS(CICCreditsScreen);
	bool bFinalCredits;
public:
	CICCreditsScreen() {}
	CICCreditsScreen( bool _bFinalCredits ): bFinalCredits( _bFinalCredits ) {}

	void Exec();
};
